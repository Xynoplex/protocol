(* bus.exe SPECS: the bus's channels as TypeScript, for the conformance
   harness. [BusPayloads<S>] is what each channel carries, given the
   gateway's component schemas as [S]: a schema's channel carries
   [S[schema]], an envelope's [{ response: S[schema] }] (EVENT-BUS.md's
   reply shapes), an empty object's an object with no member, and a void
   channel's nothing. [S] must name every schema a channel carries, so a
   document that leaves one out is refused where the harness instantiates
   it. A stored event's channel is not here: the registry does not say
   which component carries a stored event. *)

module R = Tables.Bus_registry

let json text = Yojson.Safe.to_string (`String text)

let payload : R.channels_item -> (string * string) option = function
  | Schema { channel; schema; _ } ->
      Some (channel, Printf.sprintf "S[%s]" (json schema))
  | Envelope { channel; schema; _ } ->
      Some (channel, Printf.sprintf "{ response: S[%s] }" (json schema))
  | Empty { channel; _ } -> Some (channel, "{ [member: string]: never }")
  | Void { channel; _ } -> Some (channel, "undefined")
  | Stored_event _ -> None

let carried : R.channels_item -> string option = function
  | Schema { schema; _ } | Envelope { schema; _ } -> Some schema
  | Empty _ | Void _ | Stored_event _ -> None

let () =
  let specs =
    match Sys.argv with
    | [| _; specs |] -> specs
    | _ ->
        prerr_endline "usage: bus.exe SPECS";
        exit 2
  in
  match Spec.load specs with
  | Error errors ->
      List.iter
        (fun error -> prerr_endline (Decode.error_to_string error))
        errors;
      exit 1
  | Ok spec ->
      let channels = spec.Spec.tables.bus_registry.channels in
      print_string
        "// Generated by Protocol's reader (reader/js/bus.ml) from \
         bus/registry.json. Do not edit.\n\n";
      print_string
        "/** Every component schema a channel carries, by its name. */\n";
      Printf.printf "export type BusSchema =\n%s;\n\n"
        (String.concat "\n"
           (List.map
              (fun name -> "  | " ^ json name)
              (List.sort_uniq compare (List.filter_map carried channels))));
      print_string
        "/** What each channel but a stored event's carries, given the \
         gateway's component schemas. */\n";
      print_string
        "export type BusPayloads<S extends { [K in BusSchema]: unknown }> = {\n";
      List.iter
        (fun (channel, carries) ->
          Printf.printf "  %s: %s;\n" (json channel) carries)
        (List.filter_map payload channels);
      print_string "};\n"
